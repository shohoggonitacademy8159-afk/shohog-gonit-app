# ক (২), খ (৪), গ (৪)। √3 ≈ 1.732, √2 ≈ 1.414 ধরে আসন্ন মান; প্রতিটি মান নিচে কোডে যাচাই করা
import json, os, math
from math import sqrt, tan, sin, cos, radians as R, isclose
r3, r2 = sqrt(3), sqrt(2)
def ap(x):   # দুই দশমিক পর্যন্ত আসন্ন মান — প্রকৃত মান ও √3≈1.732 উভয় ধরে একই হতে হবে না, প্রকৃত মান থেকে
    return f'{x:.2f}'
def chk(x, s): assert ap(x) == s, (x, s)

# ---------- যাচাই ----------
# ম১ ছায়া
assert isclose(math.degrees(math.atan(1/r3)),30); chk(12*r3,'20.78'); assert isclose(12*r3-12/r3,8*r3); chk(8*r3,'13.86')
# ম২ মিনার
