# ১
assert sum([3,4,5])==12 and [180*k//12 for k in (3,4,5)]==[45,60,75]
assert rad(75)==5*pi/12 and [rad(45),rad(60),rad(75)]==[pi/4,pi/3,5*pi/12]
assert simplify(6*(5*pi/12-pi/4)-pi)==0
# ২
assert rad(6)==pi/30 and abs(30*4-R(11,2)*30)==45 and rad(45)==pi/4
assert 40*rad(6)==4*pi/3 and simplify(7*4*pi/3-28*pi/3)==0 and round(28*math.pi/3,2)==29.32
# ৩
th=rad(R(32,60)); assert th==2*pi/675 and round(float(th),5)==0.00931
assert simplify(6440*th-R(2576,135)*pi)==0 and round(float(6440*th),2)==59.95
assert simplify(6450*th-R(172,9)*pi)==0 and round(float(6450*th),2)==60.04
# ৪
assert 5*2*pi==10*pi and 5*P*R(14,10)==22 and 22*R(36,10)==R(792,10)
assert 1320/(P*R(14,10))==300 and R(300,5)==60
# ৫
r1=66/(P/3); assert r1==63 and r1*R(4,3)==84 and R(66,84)==R(11,14) and R(11,14)*180/P==45 and R(60,45)==R(4,3)
# ৬
d=symbols('d'); assert solve(180*(60-d)-60*(60+d),d)==[30]
