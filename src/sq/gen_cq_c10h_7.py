# এসএসসি উচ্চতর গণিত অধ্যায় ৭ (অসীম ধারা): ৮টি সৃজনশীল প্রশ্ন — সহজ ২, মধ্যম ৪, কঠিন ২ (শুধু উত্তর)
# ক (২), খ (৪), গ (৪)। সব উত্তর কোডে যাচাই করা
import json, os
from sympy import symbols, Rational as R, sqrt, simplify, solve, limit, oo, summation, factor, nsimplify, pi, sin, tan, Abs
n,x,k=symbols('n x k',positive=True)

# ১
S=lambda m: sum(R(1,2**i) for i in range(m))
assert R(1,2**9)==R(1,512) and all(S(m)==2-R(1,2**(m-1)) for m in range(1,15))
assert min(m for m in range(1,50) if S(m)>R(199,100))==8
# ২
p=R(45,99); q=R(23,10)+R(1,100)/(1-R(1,10))
assert p==R(5,11) and q==R(104,45) and p/(1-R(1,10))==R(50,99)
# ৩
xx=symbols('xx')
assert 1/(1-R(1,3))==R(3,2)
assert simplify(1/(1-1/(1+xx))-(1+xx)/xx)==0
assert solve((1+xx)/xx-R(4,3),xx)==[3]
r=R(1,4); assert (1-r**4)/(1-r)==R(85,64)
# ৪
rr=symbols('rr'); sols=solve(12*(1-rr)*(1+rr)-R(32,3),rr); assert set(sols)=={R(1,3),R(-1,3)}
assert 12*(1-R(1,3))==8 and 12*(1+R(1,3))==16 and R(64)/(1-R(1,9))==72
# ৫
u=lambda m:(2*m+1)/(m+3)
assert [u(R(i)) for i in (1,2,3)]==[R(3,4),1,R(7,6)]
assert simplify(u(n+1)-u(n)-5/((n+3)*(n+4)))==0 and limit(u(n),n,oo)==2
assert min(m for m in range(1,2000) if abs(u(R(m))-2)<R(1,100))==498
# ৬
assert simplify(summation(1/((2*k-1)*(2*k+1)),(k,1,n))-n/(2*n+1))==0 and limit(n/(2*n+1),n,oo)==R(1,2)
assert min(m for m in range(1,200) if R(m,2*m+1)>R(49,100))==25
# ৭
assert sqrt(4**2+4**2)==4*sqrt(2) and 64/(1-R(1,2))==128
assert simplify(32/(1-1/sqrt(2))-(64+32*sqrt(2)))==0
# ৮
th=symbols('th')
assert simplify(sin(pi/4)**2/(1-sin(pi/4)**2))==1
assert simplify(sin(th)**2/(1-sin(th)**2)-tan(th)**2)==0
s2=R(3,4); assert s2/(1-s2)==3 and simplify(tan(pi/3)**2)==3
assert s2*(1-s2**5)/(1-s2)==R(2343,1024)

