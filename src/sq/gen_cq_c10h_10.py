# (সহজ ৭, মধ্যম ১০, কঠিন ৪) — শুধু উত্তর। 10.1 = (1 + x)ⁿ ধরনের, 10.2 = সাধারণ (x + y)ⁿ ধরনের (অ্যাপের প্রচলিত ভাগ)
import json, os
from sympy import symbols, expand, binomial as C, Rational as R, solve, sqrt, simplify
x,k,n=symbols('x k n')
cf=lambda e,i: expand(e).coeff(x,i)
r4=lambda v: f'{float(v):.4f}'
def series(e,m): return sum(cf(e,i)*x**i for i in range(m))
# পাঠ্যবই ১৬
assert [cf((1+x)**7,i) for i in range(8)]==[1,7,21,35,35,21,7,1]
assert [cf((1-x)**8,i) for i in range(4)]==[1,-8,28,-56] and r4(series((1-x)**8,4).subs(x,R(1,100)))=='0.9227'
assert cf((1+x)**7*(1-x)**8,7)==35
# পাঠ্যবই ১৭
