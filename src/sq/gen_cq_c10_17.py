# পাঠ্যবইয়ের রীতি: মধ্যক = L + (n/2 − Fc)·h/fm, প্রচুরক = L + f1/(f1+f2)·h (L = শ্রেণির নিম্নসীমা)
import json, os
from fractions import Fraction as F
from collections import Counter

def fmt(x):
    x=float(x)
    if abs(x-round(x))<1e-9: r=str(int(round(x)))
    else: r=f'{round(x,2):.2f}'.rstrip('0').rstrip('.')
    return r.replace('-','−')

def table(cls,f,head='শ্রেণি',fh='গণসংখ্যা'):
    return f"{head} | {fh}\n"+'\n'.join(f'{a}–{b} | {k}' for (a,b),k in zip(cls,f))

def stats(cls,f):
    h=cls[0][1]-cls[0][0]+1; assert all(b-a+1==h for a,b in cls) and all(cls[i+1][0]==cls[i][1]+1 for i in range(len(cls)-1))
    n=sum(f); mid=[F(a+b,2) for a,b in cls]
    mean=sum(m*k for m,k in zip(mid,f))/n
    cum=[sum(f[:i+1]) for i in range(len(f))]
    mi=next(i for i,c in enumerate(cum) if c>=F(n,2)); assert mi>0
    med=cls[mi][0]+(F(n,2)-cum[mi-1])*h/f[mi]
    mo=f.index(max(f)); assert f.count(max(f))==1 and 0<mo<len(f)-1
    f1=f[mo]-f[mo-1]; f2=f[mo]-f[mo+1]; mode=cls[mo][0]+F(f1,f1+f2)*h
    return dict(h=h,n=n,mid=mid,mean=mean,cum=cum,mi=mi,med=med,mo=mo,mode=mode)

def short_mean(cls,f):
    s=stats(cls,f); a=s['mid'][s['mo']]; h=s['h']
    u=[(m-a)/h for m in s['mid']]; su=sum(k*x for k,x in zip(f,u))
    assert a+su*h/s['n']==s['mean']
    return f"a = {fmt(a)}, h = {h}, Σfᵢuᵢ = {fmt(su)}; গড় = {fmt(a)} + ({fmt(su)}/{s['n']}) × {h} = {fmt(s['mean'])}"

def med_txt(cls,f):
    s=stats(cls,f); i=s['mi']
    return f"n/2 = {fmt(F(s['n'],2))}, মধ্যক শ্রেণি {cls[i][0]}–{cls[i][1]}; L = {cls[i][0]}, Fc = {s['cum'][i-1]}, fm = {f[i]}, h = {s['h']} ⇒ মধ্যক = {fmt(s['med'])}"

def mode_txt(cls,f):
    s=stats(cls,f); i=s['mo']; f1=f[i]-f[i-1]; f2=f[i]-f[i+1]
    return f"প্রচুরক শ্রেণি {cls[i][0]}–{cls[i][1]}; L = {cls[i][0]}, f1 = {f1}, f2 = {f2}, h = {s['h']} ⇒ প্রচুরক = {fmt(s['mode'])}"

def bucket(data,start,h):
    k=-(-(max(data)-start+1)//h); cls=[(start+i*h,start+i*h+h-1) for i in range(k)]
    f=[sum(1 for x in data if a<=x<=b) for a,b in cls]; assert sum(f)==len(data) and all(f)
    return cls,f

def rng(d): return max(d)-min(d)+1
def ncls(d,h): return -(-rng(d)//h)
def raw_med(d):
    s=sorted(d); n=len(s); return F(s[n//2]) if n%2 else F(s[n//2-1]+s[n//2],2)
def raw_mode(d):
    c=Counter(d).most_common(); assert c[0][1]>c[1][1]; return c[0][0]
def L(d): return ', '.join(map(str,d))
def boundaries(cls): return ', '.join(f'{fmt(a-0.5)}–{fmt(b+0.5)}' for a,b in cls)

