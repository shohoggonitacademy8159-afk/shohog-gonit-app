# ১ অ্যাপোলোনিয়াস
assert 7**2+9**2==2*(7**2+4**2)
# ২ মধ্যমা
a,b,c=6,8,10; assert a*a+b*b==c*c
AD2=(2*b*b+2*c*c-a*a)/4; BE2=(2*a*a+2*c*c-b*b)/4; CF2=(2*a*a+2*b*b-c*c)/4
assert (AD2,BE2,CF2)==(73,52,25) and 3*(a*a+b*b+c*c)==4*(AD2+BE2+CF2)==600
# ৩ টলেমি (AC ব্যাস)
assert sqrt(36+64)==10 and isclose((6*8+8*6)/10,9.6) and isclose(2*6*8/10,9.6)
# ৪ সমবাহু ত্রিভুজ ও টলেমি
PB,PC=3,5; BC=sqrt(PB*PB+PC*PC-2*PB*PC*cos(radians(120))); assert isclose(BC,7)
assert isclose(PB*BC+PC*BC,(PB+PC)*BC)   # PA·BC = PB·AC + PC·AB ⇒ PA = PB + PC
# ৫ ব্রহ্মগুপ্ত
assert sqrt(9+16)==5 and 5/2==2.5
# ৬ লম্ব কর্ণবিশিষ্ট বৃত্তস্থ চতুর্ভুজ
AE,EC,BE,ED=4,9,6,6; assert AE*EC==BE*ED
AB=sqrt(AE**2+BE**2); BCq=sqrt(EC**2+BE**2); CD=sqrt(EC**2+ED**2); DA=sqrt(AE**2+ED**2)
assert isclose(AB,2*sqrt(13)) and isclose(BCq,3*sqrt(13)) and isclose(CD,3*sqrt(13)) and isclose(DA,2*sqrt(13))
assert isclose((AE+EC)*(BE+ED),156) and isclose(AB*CD+BCq*DA,156)
s=(AB+BCq+CD+DA)/2; assert isclose(sqrt((s-AB)*(s-BCq)*(s-CD)*(s-DA)),78) and isclose(0.5*13*12,78)
