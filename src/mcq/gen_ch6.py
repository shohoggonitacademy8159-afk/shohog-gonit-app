def nearD(v, step=10):
    out = []
    for d in (step, -step, 2 * step, -2 * step, 3 * step, 5, -5):
        w = v + d
        if 0 < w < 360 and w != v and w not in out: out.append(w)
        if len(out) == 3: break
    return [D(w) for w in out]
