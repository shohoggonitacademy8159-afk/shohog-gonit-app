"""একাদশ উচ্চতর গণিত অধ্যায় ১ (ম্যাট্রিক্স) — অ্যাডমিন প্যানেলের "একসাথে অনেক" ঘরে পেস্ট করার জন্য নিজস্ব নতুন প্রশ্ন
(পেস্ট করলে Firestore-এ জমা হয়)। প্রতিটি সংখ্যাগত উত্তর এখানে হিসাব করে যাচাই করা হয়।
ফলাফল: /home/claude/out/h11-matrix-bulk.txt"""
import random, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
R = random.Random(20261121)
L = 'কখগঘ'
OUT = []


def mul(A, B):
    return [[sum(A[i][k] * B[k][j] for k in range(len(B))) for j in range(len(B[0]))] for i in range(len(A))]


def T(A): return [list(r) for r in zip(*A)]
def addm(A, B, s=1): return [[a + s * b for a, b in zip(x, y)] for x, y in zip(A, B)]
def sc(k, A): return [[k * a for a in r] for r in A]


def num(x):
    if isinstance(x, complex):
        a, b = int(x.real), int(x.imag)
        if b == 0: return num(a)
        bs = ('' if abs(b) == 1 else str(abs(b))) + 'i'
        if a == 0: return ('−' if b < 0 else '') + bs
        return f"{num(a)} {'−' if b < 0 else '+'} {bs}"
    if isinstance(x, str): return x
    return ('−' + str(-x)) if x < 0 else str(x)


def M(A): return '[' + ', '.join('(' + ', '.join(num(x) for x in r) + ')' for r in A) + ']'


def add(q, right, wrong, e, lv):
    ws = [w for w in dict.fromkeys(wrong) if w != right]
    assert len(ws) >= 3, (q, right, wrong)
    o = [right] + ws[:3]; R.shuffle(o)
    OUT.append((q, o, o.index(right), e, lv))


def multi(stem, st, ok, e, lv):
    combos = ['i ও ii', 'i ও iii', 'ii ও iii', 'i, ii ও iii']
    OUT.append((f'{stem}\ni. {st[0]}\nii. {st[1]}\niii. {st[2]}\nনিচের কোনটি সঠিক?', combos, {(0, 1): 0, (0, 2): 1, (1, 2): 2, (0, 1, 2): 3}[ok], e, lv))


# ---- অজানা মান: প্রতিসম, বিপ্রতিসম, ট্রেস, ত্রিভুজাকার, সমতা ----
add('[(0, 2a − 1, 6), (−7, 0, b + 3), (−6, −5, 0)] একটি বিপ্রতিসম ম্যাট্রিক্স হলে (a, b) = কত?', '(4, 2)', ['(−3, −8)', '(4, −2)', '(3, 2)'],
    'বিপ্রতিসমে aᵢⱼ = −aⱼᵢ: 2a − 1 = 7 ⇒ a = 4; b + 3 = 5 ⇒ b = 2', 'মধ্যম')
add('[(2, x + y, 5), (9, −1, x − y), (5, 3, 4)] একটি প্রতিসম ম্যাট্রিক্স হলে (x, y) = কত?', '(6, 3)', ['(3, 6)', '(6, −3)', '(9, 3)'],
    'প্রতিসমে aᵢⱼ = aⱼᵢ: x + y = 9, x − y = 3 ⇒ x = 6, y = 3', 'মধ্যম')
add('[(0, p, −4), (3, 0, q), (r, −8, 0)] বিপ্রতিসম হলে p + q + r = কত?', '9', ['−9', '1', '7'],
    'p = −3, q = 8, r = 4 ⇒ p + q + r = 9', 'মধ্যম')
add('A = [(k, 3, 1), (2, 5, 0), (−4, 1, 2k)] ম্যাট্রিক্সের ট্রেস 17 হলে k = কত?', '4', ['6', '12', '17/3'],
    'ট্রেস = k + 5 + 2k = 17 ⇒ 3k = 12 ⇒ k = 4', 'সহজ')
add('A = [(x², 1), (4, 3x)] ম্যাট্রিক্সের ট্রেস −2 হলে x = কত?', '−1 অথবা −2', ['1 অথবা 2', '−1 অথবা 2', '1 অথবা −2'],
    'x² + 3x = −2 ⇒ x² + 3x + 2 = 0 ⇒ (x + 1)(x + 2) = 0', 'কঠিন')
add('[(3, 1, 4), (a − 2, 6, 7), (b + 1, c, 9)] একটি ঊর্ধ্ব ত্রিভুজাকার ম্যাট্রিক্স হলে (a, b, c) = কত?', '(2, −1, 0)', ['(−2, 1, 0)', '(2, 1, 0)', '(0, −1, 2)'],
    'মুখ্য কর্ণের নিচের সব ভুক্তি শূন্য: a − 2 = 0, b + 1 = 0, c = 0', 'মধ্যম')
add('[(2x − y, 5), (3, x + y)] = [(4, 5), (3, 8)] হলে (x, y) = কত?', '(4, 4)', ['(4, −4)', '(3, 2)', '(2, 6)'],
    'সমতা: 2x − y = 4, x + y = 8 ⇒ 3x = 12 ⇒ x = 4, y = 4', 'মধ্যম')
add('A = [(a, b), (c, d)], B = [(2, −1), (5, 3)] এবং A = 4B হলে a + d = কত?', '20', ['5', '−4', '28'],
    'A = 4B ⇒ a = 8, d = 12 ⇒ a + d = 20', 'সহজ')

A = [[3, -1], [2, 5]]
add(f'A = {M(A)} হলে A + Aᵀ = কত?', M(addm(A, T(A))), [M(addm(A, T(A), -1)), M(sc(2, A)), M([[6, 2], [-2, 10]])], f'Aᵀ = {M(T(A))}; যোগফল প্রতিসম হয়।', 'সহজ')

# ---- ক্রম ----
add('A, B, C এর ক্রম যথাক্রমে 2 × 5, 5 × 3 এবং 3 × 4 হলে ABC এর ক্রম কত?', '2 × 4', ['5 × 3', '2 × 3', '4 × 2'], '(2 × 5)(5 × 3) = 2 × 3; তারপর (2 × 3)(3 × 4) = 2 × 4', 'সহজ')
add('A এর ক্রম 3 × 4 এবং B এর ক্রম 3 × 2 হলে AᵀB এর ক্রম কত?', '4 × 2', ['3 × 2', '2 × 4', 'সংজ্ঞায়িত নয়'], 'Aᵀ: 4 × 3; (4 × 3)(3 × 2) = 4 × 2', 'মধ্যম')
add('A এর ক্রম 4 × 1 এবং B এর ক্রম 1 × 4 হলে BA এর ক্রম কত?', '1 × 1', ['4 × 4', '4 × 1', '1 × 4'], '(1 × 4)(4 × 1) = 1 × 1', 'সহজ')
add('দুটি ম্যাট্রিক্স যোগ করা যায় কোন শর্তে?', 'উভয়ের ক্রম একই', ['উভয়ই বর্গ ম্যাট্রিক্স', 'প্রথমটির কলাম = দ্বিতীয়টির সারি', 'উভয়ের সারিসংখ্যা সমান'], 'যোগ-বিয়োগের জন্য সারি ও কলাম দুটোই সমান হতে হয়।', 'সহজ')

# ---- গুণফল ----
A = [[2, 0], [1, -3], [4, 1]]; B = [[1, 2], [-1, 0]]
add(f'A = {M(A)} এবং B = {M(B)} হলে AB = কত?', M(mul(A, B)), [M([[2, 4], [-2, 2], [3, 8]]), M([[2, 0], [-1, 0], [4, 0]]), M([[2, 4], [4, -2], [5, 8]])], f'প্রতিটি সারি × প্রতিটি কলাম: {M(mul(A, B))}', 'মধ্যম')
A = [[2, 1], [-1, 3]]
gA = addm(addm(mul(A, A), sc(-5, A)), sc(7, [[1, 0], [0, 1]]))
add(f'A = {M(A)} এবং f(x) = x² − 5x + 7 হলে f(A) = কত?', M(gA), [M([[1, 0], [0, 1]]), M([[7, 0], [0, 7]]), M([[3, 1], [-1, 5]])], f'A² = {M(mul(A, A))}; A² − 5A + 7I = {M(gA)}', 'কঠিন')
A = [[1, 1j], [1j, -1]]
A2 = [[sum(A[i][k] * A[k][j] for k in range(2)) for j in range(2)] for i in range(2)]
assert all(complex(v) == 0 for r in A2 for v in r)
add(f'A = {M(A)} (i = √−1) হলে A² = কত?', M([[0, 0], [0, 0]]), [M([[1, 0], [0, 1]]), M([[0, 2j], [2j, 0]]), M([[2, 0], [0, 2]])], '1·1 + i·i = 0, 1·i + i·(−1) = 0, i·1 + (−1)·i = 0, i·i + 1 = 0 — A শূন্যঘাতি', 'কঠিন')
# ---- প্রকার চেনা ----
nil = [[2, -1], [4, -2]]; idem = [[-1, 2], [-1, 2]]; inv = [[3, -2], [4, -3]]
assert mul(nil, nil) == [[0, 0], [0, 0]] and mul(idem, idem) == idem and mul(inv, inv) == [[1, 0], [0, 1]]
add(f'{M(nil)} ম্যাট্রিক্সটি কোন ধরনের?', 'শূন্যঘাতি', ['সমঘাতি', 'অভেদঘাতি', 'প্রতিসম'], f'বর্গ = {M(mul(nil, nil))}', 'মধ্যম')
add(f'{M(idem)} ম্যাট্রিক্সটি কোন ধরনের?', 'সমঘাতি', ['শূন্যঘাতি', 'অভেদঘাতি', 'বিপ্রতিসম'], f'বর্গ = {M(mul(idem, idem))} = নিজে', 'মধ্যম')
add(f'{M(inv)} ম্যাট্রিক্সটি কোন ধরনের?', 'অভেদঘাতি', ['সমঘাতি', 'শূন্যঘাতি', 'কর্ণ'], f'বর্গ = {M(mul(inv, inv))} = I', 'মধ্যম')
add('বর্গ ম্যাট্রিক্স A এর জন্য Aᵏ⁺¹ = A হলে A কে কী বলে (k ধনাত্মক পূর্ণসংখ্যা)?', 'পর্যায়বৃত্ত ম্যাট্রিক্স', ['শূন্যঘাতি ম্যাট্রিক্স', 'অভেদক ম্যাট্রিক্স', 'বিপ্রতিসম ম্যাট্রিক্স'], 'Aᵏ⁺¹ = A হলে পর্যায়বৃত্ত (periodic); ক্ষুদ্রতম k হলো পর্যায়কাল।', 'মধ্যম')

