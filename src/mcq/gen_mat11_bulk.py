multi('[(1, 0, 0), (2, 3, 0), (4, 5, 6)] ম্যাট্রিক্সটি—', ['বর্গ ম্যাট্রিক্স', 'নিম্ন ত্রিভুজাকার ম্যাট্রিক্স', 'প্রতিসম ম্যাট্রিক্স'], (0, 1), 'কর্ণের উপরে সব শূন্য — নিম্ন ত্রিভুজাকার; a₂₁ ≠ a₁₂ তাই প্রতিসম নয়।', 'সহজ')
multi('কোনো ম্যাট্রিক্সের সারিসংখ্যা 3 এবং কলামসংখ্যা 6 হলে—', ['ভুক্তিসংখ্যা 18', 'ম্যাট্রিক্সটি আয়তাকার', 'এর ট্রান্সপোজের ক্রম 6 × 3'], (0, 1, 2), 'তিনটিই সত্য।', 'সহজ')
multi('A = [(0, 5, −2), (−5, 0, 3), (2, −3, 0)] হলে—', ['Aᵀ = −A', 'A বিপ্রতিসম ম্যাট্রিক্স', 'A এর ট্রেস 0'], (0, 1, 2), 'aᵢⱼ = −aⱼᵢ এবং কর্ণ শূন্য — তিনটিই সত্য।', 'মধ্যম')
multi('কর্ণ ম্যাট্রিক্স A = [aᵢⱼ] এর ক্ষেত্রে—', ['i ≠ j হলে aᵢⱼ = 0', 'A একটি বর্গ ম্যাট্রিক্স', 'i = j হলে aᵢⱼ ≠ 0 হতেই হবে'], (0, 1), 'কর্ণের কোনো ভুক্তি শূন্যও হতে পারে, তাই iii বাধ্যতামূলক নয়।', 'মধ্যম')
