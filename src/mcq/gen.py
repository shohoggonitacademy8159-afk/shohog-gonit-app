def _bump(s, k):
    """সংখ্যাযুক্ত অপশনের প্রথম সংখ্যাকে k বাড়িয়ে নতুন বিকল্প"""
    m = _re.search(r'\d+(\.\d+)?', s)
    if not m: return None
    v = float(m.group()); nv = v + k
    if nv <= 0: return None
    t = f"{nv:g}"
    return s[:m.start()] + t + s[m.end():]

def Q(lst, q, correct, wrong, e, lv):
    correct = str(correct)
    opts = [correct]
    for w in wrong:
        w = str(w)
        if w not in opts: opts.append(w)
    k = 1
    while len(opts) < 4:
        for cand in (_bump(correct, k), _bump(correct, -k)):
            if cand and cand not in opts and len(opts) < 4: opts.append(cand)
        k += 1
        assert k < 50, (q, opts)
    assert len(opts) == 4 and len(set(opts)) == 4, (q, opts)
    order = list(range(4)); R.shuffle(order)
    o = [opts[i] for i in order]
    lst.append({'q': q, 'o': o, 'a': o.index(str(correct)), 'e': e, 'lv': lv})

def frac(f):
    f = F(f)
    return str(f.numerator) if f.denominator == 1 else f"{f.numerator}/{f.denominator}"

def near(x, k=3, lo=1):
    """x ছাড়া কাছাকাছি k টি আলাদা পূর্ণসংখ্যা"""
    s = set()
    for d in [1, -1, 2, -2, 3, 4, -3, 5, 10, -4]:
        v = x + d
        if v >= lo and v != x: s.add(v)
        if len(s) == k: break
    return list(s)

