import json, random, pathlib
from fractions import Fraction as Fr

R = random.Random(1717)
OUT = []


def fmt(x):
    if isinstance(x, Fr):
        x = float(x)
    if isinstance(x, float):
        r = round(x, 2)
        x = str(int(r)) if r == int(r) else (f'{r:.2f}'.rstrip('0').rstrip('.'))
    return str(x).replace('-', '−') if str(x).startswith('-') else str(x)


def add(q, right, wrong, e, lv):
    right = fmt(right) if not isinstance(right, str) else right
    ws = []
    for w in wrong:
        w = fmt(w) if not isinstance(w, str) else w
        if w != right and w not in ws:
            ws.append(w)
    assert len(ws) >= 3, (q, right, wrong)
    o = [right] + ws[:3]
    R.shuffle(o)
    OUT.append({'q': q, 'o': o, 'a': o.index(right), 'e': e, 'lv': lv})


def table(head, cls, fr):
    return f"\n{head[0]} | " + ' | '.join(cls) + f"\n{head[1]} | " + ' | '.join(map(str, fr)) + "\n"


