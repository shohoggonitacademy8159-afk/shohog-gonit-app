# ---------- সারণিভিত্তিক (নিজস্ব উপাত্ত) ----------
def grouped(lo, h, f):
    cls = [(lo + i * h, lo + i * h + h - 1) for i in range(len(f))]
    lab = [f'{a}-{b}' for a, b in cls]
    n = sum(f); cf = [sum(f[:i + 1]) for i in range(len(f))]
    return cls, lab, n, cf

