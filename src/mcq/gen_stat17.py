# ---------- বহুপদী সমাপ্তিসূচক (i, ii, iii) ----------
def multi(stem, st, ok, e, lv):
    combos = ['i ও ii', 'i ও iii', 'ii ও iii', 'i, ii ও iii']
    right = {(0, 1): 0, (0, 2): 1, (1, 2): 2, (0, 1, 2): 3}[tuple(ok)]
