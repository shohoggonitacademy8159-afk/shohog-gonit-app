def mul(A, B):
    return [[sum(A[i][k] * B[k][j] for k in range(len(B))) for j in range(len(B[0]))] for i in range(len(A))]


def T(A):
    return [list(r) for r in zip(*A)]


def num(x):
    if isinstance(x, complex):
        a, b = int(x.real), int(x.imag)
        if b == 0: return num(a)
        bs = ('' if abs(b) == 1 else str(abs(b))) + 'i'
        if a == 0: return ('−' if b < 0 else '') + bs
        return f"{num(a)} {'−' if b < 0 else '+'} {bs}"
    return ('−' + str(-x)) if x < 0 else str(x)


def M(A):
    return '[' + ', '.join('(' + ', '.join(num(x) if not isinstance(x, str) else x for x in r) + ')' for r in A) + ']'


def add(q, right, wrong, e, lv, ex='1.A'):
    ws = [w for w in dict.fromkeys(wrong) if w != right]
    assert len(ws) >= 3, (q, right, wrong)
    o = [right] + ws[:3]; R.shuffle(o)
    OUT.append({'q': q, 'o': o, 'a': o.index(right), 'e': e, 'lv': lv, 'ex': ex})


def pick(q, cands, test, e, lv, name):
    """একাধিক ম্যাট্রিক্সের মধ্যে ঠিক একটি শর্ত পূরণ করে — যাচাইসহ।"""
    ok = [c for c in cands if test(c)]
    assert len(ok) == 1, (name, ok)
    add(q, M(ok[0]), [M(c) for c in cands if c is not ok[0]], e, lv)


